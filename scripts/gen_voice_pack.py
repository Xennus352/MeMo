#!/usr/bin/env python3
"""Generate MeMo's built-in Shoon voice pack (fixed Burmese lines) as small m4a files."""
import json, os, re, subprocess, sys, urllib.request

ROOT = "/home/kazue/Projects/Personal/Memo"
OUT = os.path.join(ROOT, "src", "public", "voice")
TS = os.path.join(ROOT, "src", "lib", "voicePack.ts")
TMP = "/tmp/opencode/voice-tmp"
os.makedirs(OUT, exist_ok=True)
os.makedirs(TMP, exist_ok=True)

src = open(os.path.join(ROOT, "src", "lib", "careMessages.ts"), encoding="utf-8").read()
m = re.search(r"PERIOD_CARE_MESSAGES: string\[\] = \[(.*?)\];", src, re.S)
care = re.findall(r"^\s*'(.*)',\s*$", m.group(1), re.M)
assert len(care) == 20, f"expected 20 care messages, got {len(care)}"

mm = lambda n: str(n).translate(str.maketrans("0123456789", "၀၁၂၃၄၅၆၇၈၉"))
items = []
for i, text in enumerate(care, 1):
    items.append((f"care-{i:02d}", text))
items.append(("period-today", "ဒီနေ့ သင့်ရာသီ စတင်တော့မယ် 💕"))
for d in range(1, 8):
    items.append((f"period-{d}", f"သင့်ရာသီ နောက်ထပ် {mm(d)} ရက်အတွင်း 💕"))
items.append(("period-ended", "ရာသီကုန်ပြီ — အားမာန်ရှိပါတယ် 🌸"))
items.append(("fertility", "ဒီနေ့ မျိုးပွားနိုင်အောင်ချိန်ပါ ✨"))
items.append(("ovulation", "ဒီနေ့ မျိုးဥအထွက်ဆုံးနေ့ ✨"))
items.append(("test", "မင်္ဂလာပါ။ သင်၏ အသိပေးချက်များကို ဤအသံဖြင့် ကြားရမှာဖြစ်ပါတယ်။"))

# Keep Burmese letters, ASCII text/digits, spaces and sentence punctuation.
KEEP = re.compile(r"[^\u1000-\u109F\uAA60-\uAA7Fa-zA-Z0-9 .,!?။၊—\-]")
def spoken(text: str) -> str:
    cleaned = KEEP.sub(" ", text)
    return re.sub(r"\s+", " ", cleaned).strip()

def synth(text: str) -> bytes:
    req = urllib.request.Request(
        "http://127.0.0.1:8899/tts",
        data=json.dumps({"text": text}).encode(),
        headers={"Content-Type": "application/json"},
    )
    with urllib.request.urlopen(req, timeout=300) as r:
        return r.read()

manifest = []
for name, text in items:
    say = spoken(text)
    wav = os.path.join(TMP, f"{name}.wav")
    m4a = os.path.join(OUT, f"{name}.m4a")
    with open(wav, "wb") as f:
        f.write(synth(say))
    subprocess.run(
        ["ffmpeg", "-y", "-loglevel", "error", "-i", wav,
         "-ac", "1", "-ar", "24000", "-c:a", "aac", "-b:a", "40k", "-movflags", "+faststart", m4a],
        check=True,
    )
    manifest.append({"name": name, "text": text, "spoken": say, "file": f"{name}.m4a"})
    print(f"{name:14s} {os.path.getsize(m4a)/1024:7.1f} KB  {text[:34]}")

json.dump(manifest, open("/tmp/opencode/voice-manifest.json", "w", encoding="utf-8"), ensure_ascii=False, indent=2)

lines = [
    "/**",
    " * Built-in voice pack — the fixed Burmese reminder lines pre-recorded with",
    " * Nara Mini v1 (Shoon voice) and shipped with the app. Phones with no",
    " * Burmese system voice and no reachable Nara server still speak these.",
    " *",
    " * Nara Mini v1 is Apache 2.0 by the Nara contributors — https://naraaudio.app",
    " * Generated by scripts/gen_voice_pack.py; do not hand-edit the map.",
    " */",
    "",
    "const VOICE_FILES: Record<string, string> = {",
]
for row in manifest:
    text = row["text"].replace("\\", "\\\\").replace("'", "\\'")
    lines.append(f"  '{text}': '{row['file']}',")
lines += [
    "};",
    "",
    "/** Bundled audio URL for `text`, or null when the line isn't pre-recorded. */",
    "export const builtinVoiceUrl = (text: string): string | null => {",
    "  const file = VOICE_FILES[text.trim()];",
    "  return file ? `${import.meta.env.BASE_URL}voice/${file}` : null;",
    "};",
    "",
    "/** Fetch the bundled audio bytes (used to pre-cache locked-phone alarms). */",
    "export const fetchBuiltinVoice = async (text: string): Promise<Blob | null> => {",
    "  const url = builtinVoiceUrl(text);",
    "  if (!url) return null;",
    "  try {",
    "    const res = await fetch(url);",
    "    if (!res.ok) return null;",
    "    return await res.blob();",
    "  } catch {",
    "    return null;",
    "  }",
    "};",
    "",
    "/** True when the line can be spoken entirely offline from the bundle. */",
    "export const hasBuiltinVoice = (text: string): boolean => builtinVoiceUrl(text) !== null;",
    "",
]
open(TS, "w", encoding="utf-8").write("\n".join(lines))
print(f"\n{len(manifest)} clips -> {OUT}\nmap -> {TS}")
